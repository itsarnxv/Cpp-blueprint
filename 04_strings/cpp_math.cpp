#include <iostream>
#include <cmath>
#include <algorithm>   // For max() and min()

using namespace std;

int main()
{
    cout << max(5, 10) << endl;
    cout << min(5, 10) << endl;
    cout << "Square root of 64 is: " << sqrt(64) << endl;
    cout << "Round 2.6 to the nearest integer: " << round(2.6) << endl;
    cout << "The natural logarithm of 2 is: " << log(2) << endl;

    return 0;
}