#include <iostream>
using namespace std;

int main() {
    int x = 10, y = 5;

    // Equal to (==)
    cout << "x == y : " << (x == y) << endl;

    // Not equal to (!=)
    cout << "x != y : " << (x != y) << endl;

    // Greater than (>)
    cout << "x > y : " << (x > y) << endl;

    // Less than (<)
    cout << "x < y : " << (x < y) << endl;

    // Greater than or equal to (>=)
    cout << "x >= y : " << (x >= y) << endl;

    // Less than or equal to (<=)
    cout << "x <= y : " << (x <= y) << endl;

    return 0;
}